import pg from "pg";
import dotenv from "dotenv";
import path from "path";
dotenv.config({ path: path.join(import.meta.dirname, "../.env") });

const client = new pg.Client({
  connectionString: process.env.DATABASE_URL,
  ssl: false,
});

async function run() {
  await client.connect();
  console.log("Conectado a PostgreSQL en Supabase...");

  const sql = `
    -- 1. Nuevas columnas en tabla juegos
    alter table juegos add column if not exists dispositivo text not null default 'ambos';
    alter table juegos add column if not exists version text default '1.0';
    alter table juegos add column if not exists novedades text;
    alter table juegos add column if not exists actualizado_en timestamptz;
    alter table juegos add column if not exists actualizacion_pendiente jsonb;

    create index if not exists juegos_dispositivo_idx on juegos (dispositivo);

    -- 2. Tabla de puntuaciones y progreso por estudiante
    create table if not exists juegos_puntuaciones (
      id bigint generated by default as identity primary key,
      juego_id bigint not null references juegos(id) on delete cascade,
      estudiante_documento text not null,
      estudiante_nombre text not null,
      estudiante_grado text,
      puntuacion integer not null default 0,
      nivel integer default 1,
      datos jsonb,
      updated_at timestamptz default now(),
      constraint juegos_puntuaciones_unicas unique(juego_id, estudiante_documento)
    );

    create index if not exists juegos_puntuaciones_juego_idx on juegos_puntuaciones (juego_id, puntuacion desc);
    create index if not exists juegos_puntuaciones_estudiante_idx on juegos_puntuaciones (estudiante_documento);

    -- 3. Establecer dispositivos coherentes para los juegos demo existentes
    update juegos set dispositivo = 'ambos' where tipo = 'html_archivo' and titulo like '%ReciclaTech%';
    update juegos set dispositivo = 'ambos' where tipo = 'html_archivo' and titulo like '%2D%';
    update juegos set dispositivo = 'pc' where tipo = 'html_archivo' and titulo like '%3D%';
  `;

  await client.query(sql);
  console.log("✅ Migración v2 exitosa: campos de juegos y tabla 'juegos_puntuaciones' listos.");
  await client.end();
}

run().catch((err) => {
  console.error("❌ Error en migración v2:", err);
  process.exit(1);
});
