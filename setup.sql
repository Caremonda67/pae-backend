-- 1. Tabla de menus: el catalogo semanal que se publica
-- El PAE rota el menu por SEMANA del mes (1-4) y cada dia tiene una
-- comida DIFERENTE por jornada: una para Almuerzo y otra para Refrigerio.
-- Por eso cada fila es: semana + dia + jornada + platillo.
create table if not exists menus (
  id bigint generated by default as identity primary key,
  semana integer not null default 1,
  dia text not null,
  jornada text not null default 'Almuerzo',
  platillo text not null,
  descripcion text,
  calorias integer,
  imagen text,
  created_at timestamptz default now()
);

-- Migracion para bases que ya existian con el modelo anterior
-- (la columna "jornadas" era una lista). Se crean las columnas nuevas
-- si faltan, cada fila se queda con su primera jornada y se agrega
-- semana = 1. La columna vieja se elimina.
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_name = 'menus' and column_name = 'jornadas'
  ) then
    alter table menus add column if not exists semana integer not null default 1;
    alter table menus add column if not exists jornada text not null default 'Almuerzo';
    update menus
    set jornada = case when array_length(jornadas, 1) >= 1 then jornadas[1] else 'Almuerzo' end
    where jornada is null or jornada = 'Almuerzo';
    execute 'alter table menus drop column jornadas';
  end if;
end $$;

-- 2. Tabla de reservas: los estudiantes que confirman comida
create table if not exists reservas (
  id bigint generated by default as identity primary key,
  estudiante text not null,
  documento text not null,
  sede text not null,
  turno text not null,
  fecha date not null,
  asistio boolean default false,
  grado text,
  created_at timestamptz default now()
);

-- Si la tabla ya existia sin la columna de asistencia, se agrega aca
alter table reservas add column if not exists asistio boolean default false;

-- El grado se guarda en cada reserva para saber el horario de su turno
alter table reservas add column if not exists grado text;

-- 2.1 Para llevar: la reserva puede indicar que la minuta se empaca
-- para llevarla a casa (Grab & Go). Ademas cada reserva tiene un
-- codigo corto unico (ej: 4K7QX2) que se imprime en la hoja de
-- entrega para que la cocina empare por nombre sin confundirse.
alter table reservas add column if not exists para_llevar boolean default false;
alter table reservas add column if not exists codigo text;
create index if not exists idx_reservas_codigo on reservas (codigo);

-- 3. Tabla de contactos: mensajes del formulario de contacto
create table if not exists contactos (
  id bigint generated by default as identity primary key,
  nombre text not null,
  correo text not null,
  mensaje text not null,
  created_at timestamptz default now()
);

-- Contactos: el admin puede marcarlos como leidos y responderles.
-- "documento" vincula el mensaje a un estudiante registrado (su
-- usuario en la tabla usuarios), asi ese estudiante ve la respuesta
-- al entrar con su sesion. "imagen" guarda la URL de una foto que
-- el remitente adjunto y "respuesta" la contestacion del admin.
alter table contactos add column if not exists leido boolean default false;
alter table contactos add column if not exists documento text;
alter table contactos add column if not exists imagen text;
alter table contactos add column if not exists respuesta text;
alter table contactos add column if not exists respuesta_at timestamptz;

