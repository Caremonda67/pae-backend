  id bigint generated by default as identity primary key,
  tipo text not null,
  estudiante text not null,
  documento text,
  sede text not null,
  grado text,
  descripcion text not null,
  fecha date not null,
  reportado_por text not null,
  resuelto boolean default false,
  resuelto_por text,
